const id = () => youtubeVideoId(location.href);
const videoTitle = () =>
  document
    .querySelector(
      "ytd-reel-video-renderer[is-active] h2, ytd-reel-video-renderer[is-active] #title",
    )
    ?.textContent?.trim() ||
  document.querySelector("h1.ytd-watch-metadata")?.textContent?.trim() ||
  document.title.replace(/ - YouTube$/, "");
const videoElement = () =>
  document.querySelector("ytd-reel-video-renderer[is-active] video") ||
  [...document.querySelectorAll("video.html5-main-video")].find(
    (v) => !v.paused && v.readyState >= 2,
  ) ||
  document.querySelector("video.html5-main-video");
let current = null,
  lease = 0,
  interval = 5,
  resolution = 1600,
  lastCapture = 0,
  lastPrint = null,
  busy = false,
  epoch = 0,
  endedVideo = null,
  lastSnapshot = 0,
  navigationStarted = 0,
  resumeUntil = 0,
  captionController = null;
const send = async (m) => {
  const r = await chrome.runtime.sendMessage(m);
  if (r?.error) throw new Error(r.error);
  return r?.data;
};
async function captions(videoId, token) {
  const result = await new TranscriptFetcher(captionController?.signal).fetch(
    videoId,
  );
  if (current !== videoId || epoch !== token) return;
  if (result.title && result.title !== "YouTube")
    await send({
      type: "SESSION",
      videoId,
      title: result.title,
      audioPrimary:
        /Provided to YouTube by/.test(
          document.querySelector("#description-inline-expander")?.textContent ||
            "",
        ) &&
        /Auto-generated by YouTube/.test(
          document.querySelector("#description-inline-expander")?.textContent ||
            "",
        ),
    });
  await send({
    type: "TRANSCRIPT",
    videoId,
    segments: result.transcript,
    source: result.source,
    status: result.status,
    message: result.message,
    autoRequested: Date.now() < lease,
  });
}
