async function navigate(force = false) {
  const next = id();
  if (next === current && !force) return;
  const resume = Date.now() < Math.max(lease, resumeUntil);
  current = next;
  const token = ++epoch;
  captionController?.abort();
  captionController = new AbortController();
  lease = next && resume ? Date.now() + 15000 : 0;
  resumeUntil = 0;
  lastPrint = null;
  lastCapture = 0;
  lastSnapshot = 0;
  endedVideo = null;
  ensureLauncher();
  if (!next) return;
  ensureLauncher();
  await send({
    type: "SESSION",
    videoId: next,
    title:
      document.querySelector("h1.ytd-watch-metadata")?.textContent?.trim() ||
      document.title.replace(/ - YouTube$/, ""),
  });
  captions(next, token).catch(() => {
    if (current === next && epoch === token)
      send({ type: "TRANSCRIPT", videoId: next, segments: [] }).catch(() => {});
  });
}
async function capture(manual = false) {
  const video = videoElement();
  if (
    busy ||
    navigationStarted ||
    !current ||
    !video ||
    video.readyState < 2 ||
    document.querySelector(
      "#movie_player.ad-showing, #movie_player.ad-interrupting",
    ) ||
    document.hidden
  )
    return;
  if (
    !manual &&
    (Date.now() > lease ||
      video.paused ||
      Date.now() - lastCapture < interval * 1000)
  )
    return;
  busy = true;
  const videoId = current,
    token = epoch;
  lastCapture = Date.now();
  try {
    const canvas = document.createElement("canvas");
    canvas.width = Math.min(resolution, video.videoWidth);
    canvas.height = Math.round(
      (canvas.width * video.videoHeight) / video.videoWidth,
    );
    const ctx = canvas.getContext("2d", { willReadFrequently: true });
    ctx.drawImage(video, 0, 0, canvas.width, canvas.height);
    const small = document.createElement("canvas");
    small.width = 160;
    small.height = 90;
    const sc = small.getContext("2d", { willReadFrequently: true });
    sc.drawImage(canvas, 0, 0, 160, 90);
    const signal = frameSignal(sc.getImageData(0, 0, 160, 90).data, 160, 90);
    const periodic = !lastSnapshot || Date.now() - lastSnapshot >= 60000;
    if (
      !manual &&
      !periodic &&
      (!signal.useful || frameDifference(lastPrint, signal.fingerprint) < 8)
    )
      return;
    const image = canvas.toDataURL("image/jpeg", 0.65);
    if (current !== videoId || epoch !== token) return;
    const reason = manual
      ? "manual snapshot"
      : periodic
        ? "periodic snapshot"
        : "visual change";
    const result = await send({
      type: "FRAME",
      videoId,
      timestamp: video.currentTime,
      image,
      reason,
    });
    if (result?.skipped) return;
    lastSnapshot = Date.now();
    lastPrint = signal.fingerprint;
  } catch {
    lease = 0;
    send({ type: "CAPTURE_ERROR", videoId }).catch(() => {});
  } finally {
    busy = false;
  }
}
chrome.runtime.onMessage.addListener((m, sender, respond) => {
  if (sender.id !== chrome.runtime.id) return;
  if (m.type === "GET_VIDEO") {
    respond({
      navigating: !!navigationStarted,
      videoId: current,
      title: document
        .querySelector("h1.ytd-watch-metadata")
        ?.textContent?.trim(),
      capturing: Date.now() < lease,
      currentTime: videoElement()?.currentTime || 0,
      paused: videoElement()?.paused ?? true,
      playbackRate: videoElement()?.playbackRate || 1,
      adShowing: !!document.querySelector(
        "#movie_player.ad-showing, #movie_player.ad-interrupting",
      ),
    });
    return;
  }
  if (m.videoId !== current) {
    respond({ error: "Video changed. Refresh the panel." });
    return;
  }
  if (m.type === "CAPTURE_START") {
    lease = Date.now() + 15000;
    interval = m.interval || 5;
    resolution = m.profile === "balanced" ? 960 : 1600;
    respond({ ok: true });
  }
  if (m.type === "CAPTURE_STOP") {
    lease = 0;
    respond({ ok: true });
  }
  if (m.type === "CAPTURE_ONCE") {
    capture(true);
    respond({ ok: true });
  }
  if (m.type === "SEEK") {
    const video = videoElement();
    if (video) video.currentTime = Math.max(0, Number(m.timestamp) || 0);
    respond({ ok: true });
  }
  if (m.type === "RETRY_CAPTIONS") {
    captions(current, epoch).catch(() => {});
    respond({ ok: true });
  }
});
document.addEventListener("yt-navigate-finish", () => {
  navigationStarted = 0;
  navigate(true).catch(() => {});
});
document.addEventListener("yt-navigate-start", () => {
  navigationStarted = Date.now();
  resumeUntil = Math.max(resumeUntil, lease);
  lease = 0;
  ++epoch;
  captionController?.abort();
});
setInterval(() => {
  if (!chrome.runtime?.id) return;
  ensureLauncher();
  if (navigationStarted && Date.now() - navigationStarted > 10000) {
    navigationStarted = 0;
    navigate(true).catch(() => {});
  } else if (!navigationStarted && id() !== current) navigate().catch(() => {});
  capture().catch(() => {});
  const video = videoElement();
  if (video?.ended && current && endedVideo !== current) {
    endedVideo = current;
    send({ type: "ENDED", videoId: current }).catch(() => {});
  }
}, 1000);
navigate().catch(() => {});
