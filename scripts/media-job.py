import json, os, sys, subprocess, csv
import yt_dlp
import imageio_ffmpeg
video_id, directory = sys.argv[1:3]
if len(video_id) != 11 or any(c not in 'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789_-' for c in video_id):
    raise ValueError('Invalid video identifier')
url = 'https://www.youtube.com/watch?v=' + video_id
options = {
    'quiet': True, 'no_warnings': True, 'noplaylist': True,
    'format': 'bestaudio[abr<=80]/bestaudio', 'outtmpl': os.path.join(directory, 'source.%(ext)s'),
    'max_filesize': 150 * 1024 * 1024, 'socket_timeout': 20, 'retries': 2,
    'ffmpeg_location': imageio_ffmpeg.get_ffmpeg_exe(),
    'postprocessors': [{'key': 'FFmpegExtractAudio', 'preferredcodec': 'mp3', 'preferredquality': '64'}],
    'js_runtimes': {'node': {}},
}
with yt_dlp.YoutubeDL(options) as extractor:
    info = extractor.extract_info(url, download=False)
    if info.get('is_live') or (info.get('duration') or 0) > 7200:
        raise ValueError('Live streams and videos over two hours require watching capture or manual audio import.')
    extractor.extract_info(url, download=True)
subprocess.run([imageio_ffmpeg.get_ffmpeg_exe(), '-hide_banner', '-loglevel', 'error', '-i', os.path.join(directory, 'source.mp3'), '-f', 'segment', '-segment_time', '1200', '-segment_list', os.path.join(directory, 'chunks.csv'), '-segment_list_type', 'csv', '-c', 'copy', os.path.join(directory, 'chunk-%03d.mp3')], check=True, timeout=120)
with open(os.path.join(directory, 'chunks.csv'), newline='', encoding='utf8') as source:
    chunks = [{'name': os.path.basename(row[0]), 'start': float(row[1]), 'end': float(row[2]), 'bytes': os.path.getsize(os.path.join(directory, os.path.basename(row[0])))} for row in csv.reader(source)]
metadata = {
    'videoId': video_id, 'title': info.get('title', 'YouTube video'),
    'duration': info.get('duration'), 'audioPrimary': 'Auto-generated by YouTube' in info.get('description', '') and 'Provided to YouTube by' in info.get('description', ''),
    'captionLanguages': list(info.get('subtitles', {}).keys()),
    'chunks': chunks,
}
with open(os.path.join(directory, 'metadata.json'), 'w', encoding='utf8') as target:
    json.dump(metadata, target, ensure_ascii=False)
